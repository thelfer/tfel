#undef NDEBUG
#endif /* NDEBUG */

#include <cmath>
#include <cstdlib>
#include <iostream>
#include "TFEL/Tests/TestCase.hxx"
#include "TFEL/Tests/TestProxy.hxx"
#include "TFEL/Tests/TestManager.hxx"
#include "TFEL/Math/stensor.hxx"
#include "TFEL/Math/tensor.hxx"
#include "TFEL/Math/st2tost2.hxx"
#include "TFEL/Math/t2tost2.hxx"
#include "TFEL/Math/t2tot2.hxx"
#include "TFEL/Material/FiniteStrainBehaviourTangentOperator.hxx"

struct FiniteStrainBehaviourTangentOperator16 final
    : public tfel::tests::TestCase {
  FiniteStrainBehaviourTangentOperator16()
      : tfel::tests::TestCase("TFEL/Material",
                              "FiniteStrainBehaviourTangentOperator16") {
  }  // end of FiniteStrainBehaviourTangentOperator16
  tfel::tests::TestResult execute() override {
    this->check<1u>();
    this->check<2u>();
    this->check<3u>();
    return this->result;
  }  // end of execute

 private:
  template <unsigned short N>
  void check() {
    using namespace tfel::material;
    using TangentOperator = FiniteStrainBehaviourTangentOperatorBase;
    using real = double;
    using stensor = tfel::math::stensor<N, real>;
    using tensor = tfel::math::tensor<N, real>;
    using st2tost2 = tfel::math::st2tost2<N, real>;
    using t2tost2 = tfel::math::t2tost2<N, real>;
    using t2tot2 = tfel::math::t2tot2<N, real>;
    using Variant = FiniteStrainBehaviourTangentOperator<N, real>;
    const auto size = tfel::math::TensorDimeToSize<N>::value;
    const auto check_equal = [this, size](const t2tot2& a, const t2tot2& b) {
      for (unsigned short i = 0; i != size; ++i) {
        for (unsigned short j = 0; j != size; ++j) {
          // the values must be identical
          TFEL_TESTS_ASSERT(a(i, j) == b(i, j));
        }
      }
    };
    auto A = t2tot2{};
    auto B = t2tot2{};
    for (unsigned short i = 0; i != size; ++i) {
      for (unsigned short j = 0; j != size; ++j) {
        A(i, j) = real(1 + i + 10 * j);
        B(i, j) = real(3 * i) - real(j);
      }
    }
    const t2tot2 C = A + 2 * B;
    // assignment of a value to an empty variant
    {
      auto Dt = Variant{};
      Dt = A;
      TFEL_TESTS_ASSERT(Dt.template is<t2tot2>());
      check_equal(Dt.template get<t2tot2>(), A);
      // assignment of an expression to a variant holding a value of the same
      // type
      Dt = A + 2 * B;
      TFEL_TESTS_ASSERT(Dt.template is<t2tot2>());
      check_equal(Dt.template get<t2tot2>(), C);
    }
    // assignment to a variant holding a value of another type
    {
      auto Dt = Variant{t2tost2{}};
      TFEL_TESTS_ASSERT(Dt.template is<t2tost2>());
      Dt = A + 2 * B;
      TFEL_TESTS_ASSERT(Dt.template is<t2tot2>());
      check_equal(Dt.template get<t2tot2>(), C);
    }
    // assignment to a variant holding a pointer: the pointed object is
    // modified, as for the other types of tangent operators
    {
      auto K = t2tot2{};
      auto Dt = Variant{&K};
      Dt = A;
      TFEL_TESTS_ASSERT(Dt.template is<t2tot2*>());
      check_equal(K, A);
      Dt = A + 2 * B;
      TFEL_TESTS_ASSERT(Dt.template is<t2tot2*>());
      check_equal(K, C);
    }
    // conversion computed in the storage of the variant, as in the code
    // generated by MFront: the source is a copy of the operator previously
    // stored
    {
      const real l0 = 1.09465e+11;
      const real m0 = 5.6391e+10;
      const real v0[9u] = {1.01, 0.995,  1.02,  0.012, -0.007,
                           0.02, -0.011, 0.004, -0.009};
      const real v1[9u] = {1.03, 0.98,   1.09,   0.03, -0.012,
                           0.04, -0.028, -0.015, 0.005};
      const auto F0 = tensor{v0};
      const auto F1 = tensor{v1};
      const auto J = tfel::math::det(F1);
      const auto b = tfel::math::computeLeftCauchyGreenTensor(F1);
      const stensor s = (l0 * std::log(J) * stensor::Id() +  //
                         m0 * (b - stensor::Id())) /
                        J;
      const st2tost2 Cs = l0 * st2tost2::IxI() +  //
                          2 * (m0 - l0 * std::log(J)) * st2tost2::Id();
      const auto dtau =
          convert<TangentOperator::DTAU_DF, TangentOperator::SPATIAL_MODULI>(
              Cs, F0, F1, s);
      const auto dtau_ddF =
          convert<TangentOperator::DTAU_DDF, TangentOperator::DTAU_DF>(
              dtau, F0, F1, s);
      const auto dsig =
          convert<TangentOperator::DSIG_DF, TangentOperator::DTAU_DF>(
              dtau, F0, F1, s);
      const auto dP =
          convert<TangentOperator::DPK1_DF, TangentOperator::DSIG_DF>(
              dsig, F0, F1, s);
      auto Dt = Variant{};
      Dt = dsig;
      TFEL_TESTS_ASSERT(Dt.template is<t2tost2>());
      const t2tost2 tangentOperator_DSIG_DF = Dt.template get<t2tost2>();
      using result_type = tangent_operator<TangentOperator::DPK1_DF, N, real>;
      Dt.template set_uninitialised<result_type>();
      convert<TangentOperator::DPK1_DF, TangentOperator::DSIG_DF>(
          Dt.template get<result_type>(), tangentOperator_DSIG_DF, F0, F1, s);
      TFEL_TESTS_ASSERT(Dt.template is<t2tot2>());
      check_equal(Dt.template get<t2tot2>(), dP);
      // conversion whose result has the type of the source
      Dt = dtau_ddF;
      const t2tost2 source = Dt.template get<t2tost2>();
      using result_type2 = tangent_operator<TangentOperator::DTAU_DF, N, real>;
      Dt.template set_uninitialised<result_type2>();
      convert<TangentOperator::DTAU_DF, TangentOperator::DTAU_DDF>(
          Dt.template get<result_type2>(), source, F0, F1, s);
      TFEL_TESTS_ASSERT(Dt.template is<t2tost2>());
      const auto dtau2 =
          convert<TangentOperator::DTAU_DF, TangentOperator::DTAU_DDF>(
              dtau_ddF, F0, F1, s);
      const auto& r = Dt.template get<t2tost2>();
      for (unsigned short i = 0; i != tfel::math::StensorDimeToSize<N>::value;
           ++i) {
        for (unsigned short j = 0; j != size; ++j) {
          TFEL_TESTS_ASSERT(r(i, j) == dtau2(i, j));
        }
      }
    }
  }  // end of check
};

TFEL_TESTS_GENERATE_PROXY(FiniteStrainBehaviourTangentOperator16,
                          "FiniteStrainBehaviourTangentOperator16");

