/*!
 * \file   test-suite/material-properties/generic-parallel/compare.cxx
 * \brief  This program compares the evaluation of a material property on a
 * batch of points with the `generic-parallel` interface to the evaluation
 * with the `generic` interface, point by point.
 *
 * The values of the arguments are drawn among values which are inside and
 * outside of the bounds and of the physical bounds of the test material
 * properties, including values giving invalid results. All the combinations
 * of the following cases are tested:
 *
 * - out of bounds policy: `None`, `Warning` and `Strict`;
 * - layout: contiguous arrays, strided output and arguments, uniform first
 *   argument, batch of one point with a uniform output;
 * - execution: synchronous, or asynchronous (statistics given by the
 *   calling code, analysed by the report function once the computations are
 *   completed). The asynchronous execution policy is created from the
 *   identifier exported by the library
 *   (`<name>_generic_parallel_execution_policy`, see `makeExecutionPolicy`).
 *
 * At each point, the status of the batch is the status of the `generic`
 * interface, and the output is the value of the `generic` interface (`NaN`
 * if the evaluation fails, the computed value if it is not finite). The
 * values between two values of a strided output are not modified. The
 * summary of the batch (status, numbers of points, indices of the first
 * failure and of the first unreliable result, bounds status) is deduced
 * from the statuses of the points: as documented, the bounds status is null
 * for an invalid result.
 *
 * usage: compare generic_library batch_library function [--tolerance=t]
 * [--domain=min:max]
 *
 * The values are compared exactly, or up to the relative tolerance given by
 * the `--tolerance` option when the libraries are not compiled by the same
 * compiler or when the batch is evaluated on a device. The number of
 * values of the arguments can be restricted to an interval by the
 * `--domain` option (see `compare-all.sh`). The number of
 * arguments is read in the symbols exported by the library generated by the
 * `generic` interface. The memory holding the data is selected by
 * `runtime.hxx`.
 *
 * \date   20/10/2026
 */

#include <array>
#include <cmath>
#include <cstdio>
#include <limits>
#include <memory>
#include <random>
#include <string>
#include <vector>
#include <iterator>
#include <algorithm>
#include <cstring>
#include <string_view>
#include "runtime.hxx"
#include "MFront/GenericMaterialProperty/MaterialProperty.h"
#include "MFront/GenericParallelMaterialProperty/MaterialProperty.h"

//! \brief maximal value of the indices, meaning no point
static constexpr auto no_index =
    std::numeric_limits<mfront_gmp_size_type>::max();

//! \brief layout of the data of a batch
enum struct Layout { CONTIGUOUS, STRIDED, UNIFORM_ARGUMENT, ONE_POINT };

//! \return the name of a layout
static const char* getName(const Layout l) {
  switch (l) {
    case Layout::CONTIGUOUS:
      return "contiguous";
    case Layout::STRIDED:
      return "strided";
    case Layout::UNIFORM_ARGUMENT:
      return "uniform argument";
    case Layout::ONE_POINT:
      return "one point";
  }
  return "";
}

//! \return the name of an out of bounds policy
static const char* getName(const mfront_gmp_OutOfBoundsPolicy p) {
  if (p == GENERIC_MATERIALPROPERTY_WARNING_POLICY) {
    return "warning";
  }
  if (p == GENERIC_MATERIALPROPERTY_STRICT_POLICY) {
    return "strict";
  }
  return "none";
}

//! \brief array allocated in the memory selected by `runtime.hxx`
template <typename T>
struct Array {
  explicit Array(const std::size_t s, const T v = T{})
      : values(allocate<T>(s)), size(s) {
    std::fill(this->values, this->values + s, v);
  }
  Array(Array&&) = delete;
  Array(const Array&) = delete;
  Array& operator=(Array&&) = delete;
  Array& operator=(const Array&) = delete;
  ~Array() { deallocate(this->values); }
  T* values;
  std::size_t size;
};

//! \brief functions compared
struct Functions {
  mfront_gmp_MaterialPropertyPtr generic;
  mfront_gpmp_BatchMaterialPropertyPtr batch;
  mfront_gpmp_ReportPtr report;
  std::size_t nargs;
  //! \brief identifier of the execution policy expected by the library
  std::string execution_policy;
  //! \brief interval of the values of the arguments
  double minimum = -std::numeric_limits<double>::max();
  double maximum = std::numeric_limits<double>::max();
};

//! \return true if two values are equal up to the given relative tolerance
static bool areEqual(const double a, const double b, const double t) {
  if (std::isnan(a) || std::isnan(b)) {
    return std::isnan(a) && std::isnan(b);
  }
  if (t == 0) {
    return a == b;
  }
  if (std::isinf(a) || std::isinf(b)) {
    return a == b;
  }
  return std::abs(a - b) <= t * std::max(std::abs(a), std::abs(b));
}

/*!
 * \return true if the batch evaluation agrees with the `generic` interface
 * \param[in] f: functions
 * \param[in] n: number of points
 * \param[in] l: layout
 * \param[in] p: out of bounds policy
 * \param[in] asynchronous: if true, the evaluation is asynchronous and the
 * statistics are given by the calling code
 * \param[in] tolerance: relative tolerance on the values
 * \param[in,out] rng: random number generator
 */
static bool compare(const Functions& f,
                    const std::size_t n0,
                    const Layout l,
                    const mfront_gmp_OutOfBoundsPolicy p,
                    const bool asynchronous,
                    const double tolerance,
                    std::mt19937& rng) {
  // values inside and outside of the bounds and of the physical bounds of
  // the test material properties (temperatures in [0:*[ or in
  // [273.15:2610.15], porosities in [0:1]), and values giving invalid
  // results
  constexpr auto all_values = std::array<double, 18u>{
      -1e3, -1, -1e-3, 0,   1e-3, 0.1,  0.3,  0.5, 0.9,
      1,    2,  100,   300, 800,  2000, 3000, 1e5, 1e200};
  auto pool = std::vector<double>{};
  std::copy_if(
      all_values.begin(), all_values.end(), std::back_inserter(pool),
      [&f](const double v) { return (v >= f.minimum) && (v <= f.maximum); });
  auto draw = std::uniform_int_distribution<std::size_t>{0, pool.size() - 1};
  const auto n = (l == Layout::ONE_POINT) ? std::size_t{1} : n0;
  const auto output_stride =
      (l == Layout::STRIDED) ? 3 : ((l == Layout::ONE_POINT) ? 0 : 1);
  // values of the arguments at each point, and strides
  auto values = std::vector<std::vector<double>>(f.nargs);
  auto strides = std::vector<mfront_gmp_size_type>(f.nargs, 1);
  for (std::size_t a = 0; a != f.nargs; ++a) {
    if (l == Layout::STRIDED) {
      strides[a] = 2;
    }
    if ((l == Layout::UNIFORM_ARGUMENT) && (a == 0)) {
      strides[a] = 0;
    }
    const auto v0 = pool[draw(rng)];
    for (std::size_t i = 0; i != n; ++i) {
      values[a].push_back(strides[a] == 0 ? v0 : pool[draw(rng)]);
    }
  }
  // reference
  auto ref_values = std::vector<double>(n);
  auto ref_statuses = std::vector<int>(n);
  auto ref_bounds = std::vector<int>(n);
  for (std::size_t i = 0; i != n; ++i) {
    auto args = std::vector<double>(f.nargs);
    for (std::size_t a = 0; a != f.nargs; ++a) {
      args[a] = values[a][i];
    }
    auto s = mfront_gmp_OutputStatus{};
    ref_values[i] = f.generic(&s, args.data(), f.nargs, p);
    ref_statuses[i] = s.status;
    ref_bounds[i] = s.bounds_status;
  }
  // batch
  constexpr auto sentinel = double{-12345};
  auto output = Array<double>(
      (n - 1) * std::max(output_stride, 1) + 1 + (l == Layout::STRIDED ? 2 : 0),
      sentinel);
  auto statuses = Array<int>(n, 12);
  auto arrays = std::vector<std::unique_ptr<Array<double>>>{};
  auto fields = std::vector<mfront_gpmp_ConstField>{};
  for (std::size_t a = 0; a != f.nargs; ++a) {
    const auto s = strides[a];
    const auto size = (s == 0) ? 1 : (n - 1) * s + 1;
    arrays.push_back(std::make_unique<Array<double>>(size, sentinel));
    for (std::size_t i = 0; i != ((s == 0) ? 1 : n); ++i) {
      arrays.back()->values[i * s] = values[a][i];
    }
    fields.push_back(mfront_gpmp_ConstField{.values = arrays.back()->values,
                                            .point_stride = s});
  }
  auto statistics = Array<mfront_gpmp_Statistics>(1);
  mfront_gpmp_initializeStatistics(statistics.values);
  const auto asynchronous_policy =
      makeExecutionPolicy(f.execution_policy, {.asynchronous = true});
  const auto d = mfront_gpmp_BatchData{
      .number_of_points = n,
      .output = mfront_gpmp_Field{.values = output.values,
                                  .point_stride =
                                      static_cast<std::size_t>(output_stride)},
      .arguments = fields.empty() ? nullptr : fields.data(),
      .number_of_arguments = f.nargs,
      .out_of_bounds_policy = p,
      .statuses = statuses.values,
      .statistics = asynchronous ? statistics.values : nullptr,
      .execution_policy =
          asynchronous ? asynchronous_policy.get() : executionPolicy()};
  auto o = mfront_gpmp_OutputStatus{};
  auto r = f.batch(&o, &d);
  if (asynchronous) {
    // only the errors of the batch are reported
    if ((r != 0) || (o.status != 0)) {
      std::printf("asynchronous evaluation: status %d (%s)\n", r, o.msg);
      return false;
    }
    synchronize();
    r = f.report(&o, statistics.values);
  } else {
    synchronize();
  }
  // expected summary
  auto nfailures = mfront_gmp_size_type{};
  auto nunreliable = mfront_gmp_size_type{};
  auto first_failure = no_index;
  auto first_unreliable = no_index;
  for (std::size_t i = 0; i != n; ++i) {
    if (ref_statuses[i] < 0) {
      ++nfailures;
      first_failure = std::min(first_failure, mfront_gmp_size_type{i});
    } else if (ref_statuses[i] == 1) {
      ++nunreliable;
      first_unreliable = std::min(first_unreliable, mfront_gmp_size_type{i});
    }
  }
  const auto point =
      (first_failure != no_index) ? first_failure : first_unreliable;
  const auto status = (point == no_index) ? 0 : ref_statuses[point];
  const auto bounds_status =
      ((status == -1) || (status == 1)) ? ref_bounds[point] : 0;
  auto ok = (r == o.status) && (o.status == status) &&
            (o.number_of_failures == nfailures) &&
            (o.number_of_unreliable_results == nunreliable) &&
            (o.first_failure_index == first_failure) &&
            (o.first_unreliable_result_index == first_unreliable) &&
            (o.bounds_status == bounds_status);
  if (!ok) {
    std::printf(
        "summary: status %d (expected %d), failures %zu (%zu), first %zu "
        "(%zu), unreliable %zu (%zu), first %zu (%zu), bounds status %d "
        "(%d): %s\n",
        o.status, status, std::size_t{o.number_of_failures},
        std::size_t{nfailures}, std::size_t{o.first_failure_index},
        std::size_t{first_failure}, std::size_t{o.number_of_unreliable_results},
        std::size_t{nunreliable}, std::size_t{o.first_unreliable_result_index},
        std::size_t{first_unreliable}, o.bounds_status, bounds_status, o.msg);
  }
  // points
  auto mismatches = std::size_t{};
  for (std::size_t i = 0; i != n; ++i) {
    const auto v = output.values[i * output_stride];
    const auto expected = (ref_statuses[i] == -1)
                              ? std::numeric_limits<double>::quiet_NaN()
                              : ref_values[i];
    if ((statuses.values[i] != ref_statuses[i]) ||
        (!areEqual(v, expected, tolerance)) ||
        ((ref_statuses[i] == -1) && (!std::isnan(ref_values[i])))) {
      if (mismatches < 5) {
        std::printf(
            "point %zu: status %d (expected %d), value %.17g "
            "(expected %.17g), arguments",
            i, statuses.values[i], ref_statuses[i], v, expected);
        for (std::size_t a = 0; a != f.nargs; ++a) {
          std::printf(" %.17g", values[a][i]);
        }
        std::printf("\n");
      }
      ++mismatches;
    }
  }
  // the values between two values of a strided output, and the values
  // after the last one, are not modified
  if (l == Layout::STRIDED) {
    for (std::size_t i = 0; i != output.size; ++i) {
      if ((i % output_stride != 0) || (i > (n - 1) * output_stride)) {
        if (output.values[i] != sentinel) {
          ++mismatches;
        }
      }
    }
  }
  ok = ok && (mismatches == 0);
  std::printf(
      "%-8s %-16s %-12s | failures %4zu, unreliable %4zu | %s\n", getName(p),
      getName(l), asynchronous ? "asynchronous" : "synchronous",
      std::size_t{nfailures}, std::size_t{nunreliable}, ok ? "OK" : "FAILED");
  return ok;
}  // end of compare

int main(const int argc, const char* const* const argv) {
  if (argc < 4) {
    fail(
        "usage: compare generic_library batch_library function "
        "[--tolerance=t] [--domain=min:max]");
  }
  [[maybe_unused]] const auto runtime = Runtime{};
  const auto generic_library = std::string{argv[1]};
  const auto batch_library = std::string{argv[2]};
  const auto function = std::string{argv[3]};
  auto tolerance = 0.;
  auto minimum = -std::numeric_limits<double>::max();
  auto maximum = std::numeric_limits<double>::max();
  for (int a = 4; a != argc; ++a) {
    const auto option = std::string_view{argv[a]};
    if (option.starts_with("--tolerance=")) {
      tolerance = std::stod(std::string{option.substr(12)});
    } else if (option.starts_with("--domain=")) {
      const auto d = std::string{option.substr(9)};
      const auto c = d.find(':');
      if (c == std::string::npos) {
        fail("invalid domain '" + d + "'");
      }
      minimum = std::stod(d.substr(0, c));
      maximum = std::stod(d.substr(c + 1));
    } else {
      fail("unknown option '" + std::string{option} + "'");
    }
  }
  auto f = Functions{
      .generic = reinterpret_cast<mfront_gmp_MaterialPropertyPtr>(
          load(generic_library, function)),
      .batch = reinterpret_cast<mfront_gpmp_BatchMaterialPropertyPtr>(
          load(batch_library, function + "_generic_parallel")),
      .report = reinterpret_cast<mfront_gpmp_ReportPtr>(
          load(batch_library, function + "_generic_parallel_report")),
      .nargs = *static_cast<const unsigned short*>(
          load(generic_library, function + "_nargs")),
      .execution_policy = *static_cast<const char* const*>(load(
          batch_library, function + "_generic_parallel_execution_policy"))};
  f.minimum = minimum;
  f.maximum = maximum;
  auto ok = true;
  std::printf("%s (%zu argument(s))\n", function.c_str(), f.nargs);
  auto rng = std::mt19937{5};
  for (const auto p : {GENERIC_MATERIALPROPERTY_NONE_POLICY,
                       GENERIC_MATERIALPROPERTY_WARNING_POLICY,
                       GENERIC_MATERIALPROPERTY_STRICT_POLICY}) {
    for (const auto l : {Layout::CONTIGUOUS, Layout::STRIDED,
                         Layout::UNIFORM_ARGUMENT, Layout::ONE_POINT}) {
      if ((l == Layout::UNIFORM_ARGUMENT) && (f.nargs == 0)) {
        continue;
      }
      for (const auto asynchronous : {false, true}) {
        ok = compare(f, 1031, l, p, asynchronous, tolerance, rng) && ok;
      }
    }
  }
  return ok ? EXIT_SUCCESS : EXIT_FAILURE;
}  // end of main
